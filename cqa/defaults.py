def _call_criteria():
    items = _chat_criteria()
    by_id = {c["id"]: c for c in items}
    by_id["c1"]["description"] = ("Да — оператор поздоровался на языке клиента и представился в начале разговора. "
                                  "Скрытое имя ([Имя скрыто]) считается представлением.")
    by_id["c4"]["description"] = ("Оцените корректность и полноту консультации: ответил ли оператор на вопросы клиента, "
                                  "не дал ли ошибочную информацию, объяснил ли необходимые действия.")
    by_id["c4"]["naRule"] = "Разговор закончился до того, как клиент сформулировал запрос."
    by_id["c6"].update({
        "name": "Управление разговором и речь",
        "description": "Оцените логичность ведения разговора, понятность объяснений, отсутствие неуместных выражений, "
                       "корректность речевых формулировок и управление паузами (предупреждение об ожидании и удержании). "
                       "Транскрипт получен распознаванием речи: ошибки распознавания не считаются ошибками оператора.",
        "scale": SCALE_06_CALL,
    })
    by_id["c3"]["description"] += (" В звонке достаточно, чтобы оператор запросил идентифицирующие данные (ИИН, кодовое слово, "
                                   "SMS-код или ФИО плюс ещё одну проверочную деталь) до раскрытия данных; скрытые данные "
                                   "([Персональные данные скрыты]) означают, что клиент их назвал.")
    by_id["c1"]["naRule"] = "Запись началась после приветствия: начала разговора в транскрипте нет."
    by_id["c1"]["naAllowed"] = True
    by_id["c7"]["naRule"] = "Разговор оборвался до возможности его завершить."
    return items


